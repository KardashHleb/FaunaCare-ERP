/**
 * Анализ с точки зрения SOLID:
 *
 * 1. SRP (Single Responsibility) - ✅ СОБЛЮДЕН
 *    - Класс отвечает ТОЛЬКО за предоставление медицинских историй
 *    - Не создает животных, не выводит информацию, не валидирует данные
 *    - Четкая ответственность: шаблоны медицинских карт
 *
 * 2. OCP (Open/Closed) - ✅ СОБЛЮДЕН
 *    - Закрыт для модификаций существующих шаблонов
 *    - Открыт для расширения:
 *      а) Можно добавить новые методы getXXXHistory() без изменения существующих
 *      б) Можно создать наследника с другими шаблонами
 *      в) Можно использовать стратегию шаблонов через интерфейс
 *
 * 3. LSP (Liskov Substitution) - ✅ СОБЛЮДЕН
 *    - Все методы имеют одинаковую сигнатуру
 *    - Возвращают String, что ожидаемо для истории
 *    - Наследники могут безопасно подменять реализацию
 *
 * 4. ISP (Interface Segregation) - ✅ СОБЛЮДЕН
 *    - Нет "толстых" интерфейсов
 *    - Каждый метод предоставляет конкретную историю
 *    - Клиенты зависят только от нужных им методов
 *
 * 5. DIP (Dependency Inversion) - ✅ СОБЛЮДЕН
 *    - Не зависит от конкретных классов животных
 *    - Использует абстрактные параметры (String name, int age)
 *    - Высокоуровневый сервис (AnimalInitializer) зависит от абстракции MedicalHistoryService
 */



