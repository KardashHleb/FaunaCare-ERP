package core.interfaces;

/**
 * Анализ с точки зрения SOLID:
 *
 * 1. SRP (Single Responsibility) - ✅ СОБЛЮДЕН
 *    - Интерфейс отвечает только за кормление животных
 *    - Четкая ответственность: управление процессом кормления
 *    - Не смешивает другие аспекты (лечение, выставки и т.д.)
 *
 * 2. OCP (Open/Closed) - ✅ СОБЛЮДЕН
 *    - Закрыт для модификаций базового контракта
 *    - Открыт для расширения - новые классы животных могут реализовывать интерфейс
 *    - Можно добавить новые типы кормления без изменения интерфейса
 *
 * 3. LSP (Liskov Substitution) - ✅ СОБЛЮДЕН
 *    - Четко определенный контракт с ожидаемым поведением
 *    - Все реализации должны корректно выполнять указанные методы
 *    - Не нарушает принцип подстановки
 *
 * 4. ISP (Interface Segregation) - ✅ СОБЛЮДЕН
 *    - Минимальный интерфейс для одной ответственности
 *    - Не содержит методов, не связанных с кормлением
 *    - Клиенты зависят только от нужных им методов
 *
 * 5. DIP (Dependency Inversion) - ✅ СОБЛЮДЕН
 *    - Высокоуровневый абстрактный контракт
 *    - Модули высокого уровня зависят от этой абстракции
 *    - Позволяет легко заменять реализации
 */
public interface Feedable {

    /**
     * Метод для кормления животного
     * @param foodType тип пищи (например, "Мясо", "Зерно", "Фрукты")
     * @param amount количество пищи в граммах
     */
    void feed(String foodType, double amount);

    /**
     * Получить расписание кормления животного
     * @return строку с расписанием (например, "9:00, 15:00, 20:00")
     */
    String getFeedingSchedule();

    /**
     * Установить расписание кормления
     * @param schedule строка с расписанием
     */
    void setFeedingSchedule(String schedule);

    /**
     * Проверить, голодно ли животное
     * @return true если животное голодно и требует кормления
     */
    boolean isHungry();

    /**
     * Получить рекомендуемый тип пищи для животного
     * @return тип пищи (например, "Травоядное", "Плотоядное", "Всеядное")
     */
    String getRecommendedFoodType();
    // Абстрактный метод для получения суточной нормы в кг
    double getDailyFoodRequirement();
}