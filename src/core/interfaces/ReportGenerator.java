package core.interfaces;

/**
 * Анализ с точки зрения SOLID:
 *
 * 1. SRP (Single Responsibility) - ✅ СОБЛЮДЕН
 *    - Интерфейс отвечает за единую ответственность: генерация отчетов
 *    - Отчеты по кормлению, здоровью и выставкам - это разные аспекты одной отчетности
 *    - Класс-реализация отвечает за генерацию всех отчетов зоопарка
 *
 * 2. OCP (Open/Closed) - ✅ СОБЛЮДЕН
 *    - Закрыт для модификаций базового контракта
 *    - Открыт для расширения - можно добавить реализации с дополнительной логикой
 *    - Можно создавать специализированные генераторы отчетов
 *
 * 3. LSP (Liskov Substitution) - ✅ СОБЛЮДЕН
 *    - Четко определенный контракт с ожидаемым поведением
 *    - Все реализации должны корректно возвращать отчеты в виде строк
 *    - Не нарушает принцип подстановки
 *
 * 4. ISP (Interface Segregation) - ✅ СОБЛЮДЕН
 *    - Все методы относятся к единой ответственности - генерация отчетов
 *    - Клиенты, работающие с отчетами, обычно нуждаются во всех типах отчетов
 *    - Интерфейс не перегружен несвязанными методами
 *
 * 5. DIP (Dependency Inversion) - ✅ СОБЛЮДЕН
 *    - Высокоуровневый абстрактный контракт для генерации отчетов
 *    - Модули высокого уровня зависят от этой абстракции
 *    - Позволяет легко заменять реализации генераторов отчетов
 */
public interface ReportGenerator {

    /**
     * Сгенерировать отчет о кормлении животных
     * @param period период отчета (например, "дневной", "недельный", "месячный")
     * @return строковое представление отчета
     */
    String generateFeedingReport(String period);

    /**
     * Сгенерировать отчет о медицинских осмотрах
     * @param period период отчета
     * @return строковое представление отчета
     */
    String generateHealthReport(String period);

    /**
     * Сгенерировать отчет об участии животных в выставках
     * @param period период отчета
     * @return строковое представление отчета
     */
    String generateExhibitionReport(String period);

}