package core.interfaces;
/**
 * Анализ с точки зрения SOLID:
 *
 * 1. SRP (Single Responsibility) - ✅ СОБЛЮДЕН
 *    - Интерфейс отвечает только за участие в выставках
 *    - Четкая ответственность: подготовка, участие и управление выставками
 *    - Не смешивает другие аспекты (кормление, лечение и т.д.)
 *
 * 2. OCP (Open/Closed) - ✅ СОБЛЮДЕН
 *    - Закрыт для модификаций базового контракта
 *    - Открыт для расширения - новые классы могут реализовывать интерфейс
 *    - Можно добавить новые типы животных для выставок без изменения интерфейса
 *
 * 3. LSP (Liskov Substitution) - ✅ СОБЛЮДЕН
 *    - Четко определенный контракт с ожидаемым поведением
 *    - Все реализации должны корректно выполнять указанные методы
 *    - Не нарушает принцип подстановки
 *
 * 4. ISP (Interface Segregation) - ✅ СОБЛЮДЕН
 *    - Минимальный интерфейс для одной ответственности
 *    - Не содержит методов, не связанных с участием в выставках
 *    - Клиенты зависят только от нужных им методов
 *
 * 5. DIP (Dependency Inversion) - ✅ СОБЛЮДЕН
 *    - Высокоуровневый абстрактный контракт
 *    - Модули высокого уровня зависят от этой абстракции
 *    - Позволяет легко заменять реализации
 */
public interface ExhibitionParticipant {

    /**
     * Подготовить животное к выставке
     * Включает: уход, тренировку, проверку состояния
     */
    void prepareForExhibition();

    /**
     * Вывести животное на выставку
     * @param exhibitionName название выставки
     * @param durationMinutes продолжительность участия в минутах
     */
    void participateInExhibition(String exhibitionName, int durationMinutes);

    /**
     * Вернуть животное с выставки и обеспечить посленевые процедуры
     */
    void returnFromExhibition();

    /**
     * Проверить, доступно ли животное для участия в выставках
     * @return true если животное здорово и готово к выставкам
     */
    boolean isAvailableForExhibition();

    /**
     * Получить количество участий в выставках
     * @return число выставок, в которых участвовало животное
     */
    int getExhibitionCount();

    /**
     * Получить уровень подготовки к выставкам
     * @return уровень от 1 (новичок) до 10 (профессионал)
     */
    int getTrainingLevel();

    /**
     * Повысить уровень подготовки животного
     * @param hours количество часов тренировки
     */
    void train(int hours);

    /**
     * Получить список выставок, в которых участвовало животное
     * @return массив названий выставок
     */
    String[] getExhibitionHistory();

    /**
     * Проверить, не устало ли животное от частых выставок
     * @return true если животному нужен отдых
     */
    boolean needsRest();

    /**
     * Получить рекомендации по участию в выставках
     * @return строку с рекомендациями
     */
    String getExhibitionRecommendations();
}